-- turns.proposal_id 의 외래키를 뗀다.
--
-- 011 에서 걸어둔 것은 제안도 같은 데이터베이스에 있다고 가정한 것이었다.
-- 그런데 제안 저장소는 여전히 에이전트의 JSON 파일이고, 옮기지 않았다:
-- 제안은 이 시스템의 심장이고, 승인 게이트가 결정이 날 때까지 반환하지 않는
-- 핸들러와 한 몸이다. 그 이동은 대화·운동·캘린더·자산을 떼어내는 것과는 다른
-- 결정이라 여기에 끼워 넣지 않는다.
--
-- 그래서 이 컬럼은 조인할 수 있는 키가 아니라 가리키는 값이다. 외래키를
-- 남겨두면 카드가 열린 턴을 저장하는 것이 제안 테이블이 비어 있다는 이유로
-- 실패하고 - 그 실패는 대화가 화면에 안 나타나는 것으로 드러난다.
--
-- 제안을 Postgres 로 옮기면 이 제약을 다시 걸면 된다. 그때는 010 의 proposals
-- 테이블이 이미 기다리고 있다.
alter table turns drop constraint if exists turns_proposal_id_fkey;

comment on column turns.proposal_id is
  '제안의 id. 외래키가 아니다 - 제안은 아직 에이전트의 파일에 있다. 017 참고.';
